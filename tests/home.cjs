const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://home.test/',runScripts:'dangerously',pretendToBeVisual:true,beforeParse(w){w.HTMLElement.prototype.scrollIntoView=function(){};w.scrollTo=()=>{};}});
const d=dom.window.document,delay=()=>new Promise(r=>setTimeout(r,40));
(async()=>{for(let i=0;i<100&&!d.querySelector('.home-card');i++)await delay();
assert.ok(d.querySelector('.home-card'),'home card shown');
assert.equal(d.querySelectorAll('.lesson-card').length,0,'no lessons on home');
assert.equal(d.querySelector('.learner-bar'),null,'no learner bar on home');
assert.equal(d.querySelector('#student-ew-entry'),null,'no EW box on home');
assert.ok([...d.querySelectorAll('a')].some(a=>a.textContent==='Register your little ones'&&a.getAttribute('href').includes('parent-portal.html')));
[...d.querySelectorAll('button')].find(b=>b.textContent.includes('Start learning')).click();
for(let i=0;i<50&&!d.querySelector('.lesson-card');i++)await delay();
assert.ok(d.querySelectorAll('.lesson-card').length>0,'lessons after Start learning');
assert.equal(d.querySelector('.home-card'),null);
assert.ok([...d.querySelectorAll('button')].some(b=>b.textContent==='Home'));
[...d.querySelectorAll('button')].find(b=>b.textContent==='Home').click();await delay();
assert.ok(d.querySelector('.home-card'),'Home returns to opening page');
[...d.querySelectorAll('.subject-tile')].find(b=>b.textContent.includes('Science')).click();
for(let i=0;i<50&&!d.querySelector('.lesson-card');i++)await delay();
assert.ok([...d.querySelectorAll('.lesson-card')].every(c=>c.classList.contains('science')),'subject tile filters lessons');
dom.window.close();console.log('Passed: simple home screen, no lessons or EW box on home, Start learning, Home button, subject tiles, registration link.');
})().catch(e=>{console.error(e);dom.window.close();process.exitCode=1});
