// Usage: node content-src/build-lessons.mjs "<Subject>" <exportPrefix> <out.ts> <source.mjs>...
// Builds a lesson file from reviewed source lists. Each question: [prompt, correct, [wrong, wrong], explanation, choicePics?, promptPic?].
// Answer positions rotate 0,1,2 so they stay balanced.
import fs from 'node:fs';
const [subject,prefix,out,...srcs]=process.argv.slice(2);
const lessons=[];for(const f of srcs)lessons.push(...(await import(f)).lessons);
const J=JSON.stringify;let k=0;const pics={};
const built=lessons.map(l=>({id:l.id,grade:l.grade,subject,title:l.title,objective:l.objective,explain:l.explain,example:l.example,activity:l.activity,questions:l.q.map(([p,c,w,e,cp,pp],qi)=>{if(w.length!==2)throw new Error(l.id+' q'+qi);const pos=k++%3;const o=[...w];o.splice(pos,0,c);let ch;if(cp){if(cp.length!==3)throw new Error(l.id+' pics q'+qi);const x=[...cp.slice(1)];x.splice(pos,0,cp[0]);ch=x;}if(ch||pp)(pics[l.id]??={})[qi]={...(pp?{prompt:pp}:{}),...(ch?{choices:ch}:{})};return {prompt:p,options:o,answer:pos,explanation:e};})}));
fs.writeFileSync(out,`// ${subject} lessons. Generated by content-src/build-lessons.mjs from reviewed source lists in content-src/.
import type { Lesson } from "./learning-content";
export const ${prefix}Lessons: Lesson[] = ${J(built,null,1)};
export const ${prefix}Pictures: Record<string, Record<number, { prompt?: string; choices?: string[] }>> = ${J(pics)};
`);
console.log(built.length,'lessons',Object.keys(pics).length,'with pictures');
